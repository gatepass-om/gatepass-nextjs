export function translateToArabic(value: string) {
  const exact = arabicTranslations[value];
  if (exact) return exact;
  const pageMatch = /^Page (\d+) of (\d+)$/.exec(value);
  if (pageMatch) return `الصفحة ${pageMatch[1]} من ${pageMatch[2]}`;
  return value;
}
